# Criar um programa que lê as notas de um aluno e calcula a média
# Link do vídeo: https://youtu.be/mqcNw_dhl8I?si=DWZWKcdydRtOENTg

n1 = float(input('Digite a primeira nota: '))
n2 = float(input('Digite a segunda nota: '))
m = (n1 + n2) / 2
print(f'A média das notas {n1} e {n2} do aluno é {m:.2f}')